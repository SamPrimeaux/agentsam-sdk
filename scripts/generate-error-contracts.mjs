import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = path.join(root, 'protocol/errors/error-catalog.json');
const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));

const quote = value => JSON.stringify(value);
const tuple = values => values.map(quote).join(', ');
const union = values => values.map(quote).join(' | ');

function runtimeVocabulary() {
  const codeObject = catalog.codes.map(row => `  ${row.name}: ${quote(row.name)},`).join('\n');
  const grpcObject = catalog.codes.map(row => `  ${row.name}: ${row.grpc_status},`).join('\n');
  const httpObject = catalog.codes.map(row => `  ${row.name}: ${row.http_status},`).join('\n');
  const reasonObject = catalog.reasons.map(row => `  ${row.name.toUpperCase()}: ${quote(row.name)},`).join('\n');
  const reasonPolicy = catalog.reasons.map(row => `  ${quote(row.name)}: Object.freeze(${JSON.stringify({code:row.code,severity:row.severity,retryable:row.retryable,resolution_owner:row.resolution_owner,remediation_action:row.remediation_action})}),`).join('\n');
  const frozenObject = (name, values) => `export const ${name} = Object.freeze(Object.fromEntries([${tuple(values)}].map(value => [value.toUpperCase(), value])));`;
  return `// GENERATED by scripts/generate-error-contracts.mjs. Do not edit by hand.\nexport const ERROR_SCHEMA_VERSION = ${catalog.schema_version};\n\nexport const ERROR_CODE = Object.freeze({\n${codeObject}\n});\n\nexport const GRPC_STATUS = Object.freeze({\n${grpcObject}\n});\n\nexport const DEFAULT_HTTP_STATUS = Object.freeze({\n${httpObject}\n});\n\nexport const ERROR_REASON = Object.freeze({\n${reasonObject}\n});\n\n${frozenObject('ERROR_SEVERITY', catalog.severities)}\n${frozenObject('ERROR_SOURCE_KIND', catalog.source_kinds)}\n${frozenObject('ERROR_RESOLUTION_OWNER', catalog.resolution_owners)}\n${frozenObject('ERROR_DOMAIN', catalog.domains)}\n${frozenObject('REMEDIATION_ACTION', catalog.remediation_actions)}\n\nexport const ERROR_REASON_POLICY = Object.freeze({\n${reasonPolicy}\n});\n`;
}

