#!/usr/bin/env node
/**
 * Generates terminal block-character art from the official AgentSam mark.
 *
 *   node scripts/generate-mark-ansi.mjs          write src/ui/brand/agentsam-mark.generated.js
 *   node scripts/generate-mark-ansi.mjs --check  exit 1 when the committed file is stale
 *
 * Source of truth: assets/brand/AgentSam-Mark.svg. Never hand-edit the output.
 * Each terminal cell holds a 2x2 quadrant of samples; a cell is twice as tall as
 * it is wide, so columns = 2 * aspect * rows keeps the mark undistorted.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(root, 'assets/brand/AgentSam-Mark.svg');
const OUTPUT = path.join(root, 'src/ui/brand/agentsam-mark.generated.js');
const SIZES = { large: 20, medium: 12, small: 7 };

// bits are top-left, top-right, bottom-left, bottom-right
const QUADRANT = {
  '0000': ' ', '1000': '▘', '0100': '▝', '0010': '▖', '0001': '▗',
  '1100': '▀', '0011': '▄', '1010': '▌', '0101': '▐', '1001': '▚', '0110': '▞',
  '1110': '▛', '1101': '▜', '1011': '▙', '0111': '▟', '1111': '█',
};

const svg = fs.readFileSync(SOURCE);
const box = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(svg.toString('utf8'));
if (!box) throw new Error('AgentSam-Mark.svg has no viewBox');
const aspect = Number(box[1]) / Number(box[2]);

async function rasterize(rows) {
  const cols = Math.round(2 * aspect * rows);
  const { data } = await sharp(svg, { density: 96, limitInputPixels: false })
    .ensureAlpha().extractChannel('alpha')
    .resize(cols * 2, rows * 2, { fit: 'fill', kernel: 'lanczos3' })
    .raw().toBuffer({ resolveWithObject: true });
  const on = (x, y) => (data[y * cols * 2 + x] >= 128 ? '1' : '0');
  const lines = [];
  for (let cy = 0; cy < rows; cy += 1) {
    let line = '';
    for (let cx = 0; cx < cols; cx += 1) {
      line += QUADRANT[on(2 * cx, 2 * cy) + on(2 * cx + 1, 2 * cy) + on(2 * cx, 2 * cy + 1) + on(2 * cx + 1, 2 * cy + 1)];
    }
    lines.push(line);
  }
  return lines;
}

const marks = {};
for (const [name, rows] of Object.entries(SIZES)) marks[name] = await rasterize(rows);

const body = Object.entries(marks)
  .map(([name, lines]) => `  ${name}: Object.freeze([\n${lines.map((l) => `    ${JSON.stringify(l)},`).join('\n')}\n  ]),`)
  .join('\n');
const output = `// GENERATED by scripts/generate-mark-ansi.mjs from assets/brand/AgentSam-Mark.svg.\n// Do not edit; run \`npm run brand:mark\`.\nexport const AGENTSAM_MARK = Object.freeze({\n${body}\n});\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (current !== output) { console.error('agentsam-mark.generated.js is stale; run npm run brand:mark'); process.exit(1); }
  console.log('agentsam-mark.generated.js is current');
} else {
  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
  fs.writeFileSync(OUTPUT, output);
  console.log(`wrote ${path.relative(root, OUTPUT)}`);
}
