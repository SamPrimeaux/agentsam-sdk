#!/usr/bin/env node
/** Regenerate the operator's mental map from actual SDK authorities (never invent readiness). */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {CLI_COMMAND_CATALOG} from '../src/cli/command-catalog.js';
import {SLASH_COMMANDS} from '../src/lib/slash-commands.js';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const packages=JSON.parse(fs.readFileSync(path.join(root,'packages/catalog/generated/packages.json'),'utf8')).packages;
const physical=fs.readdirSync(path.join(root,'packages')).filter(n=>fs.existsSync(path.join(root,'packages',n,'package.json')));
const appnames=fs.readdirSync(path.join(root,'apps')).filter(n=>fs.existsSync(path.join(root,'apps',n,'package.json'))).sort();
const group=(items,key)=>Object.groupBy(items,item=>String(item[key]||'other'));
const clean=s=>String(s??'').replace(/\|/g,'\\|').replace(/[\r\n]+/g,' ').trim();
const list=[];
list.push('# AgentSam SDK — source-derived capability inventory','',
  '> Generated by `npm run catalog:inventory`. Do not edit manually.',
  '> **Listing ≠ operational proof.** Presence in a command, package, or app manifest is not runtime readiness; use a verified quality receipt for readiness.',
  '',`- CLI commands: **${CLI_COMMAND_CATALOG.length}** (aliases not counted)`,
  `- In-shell slash commands: **${SLASH_COMMANDS.length}**`,
  `- Package catalog registrations: **${packages.length}**`,
  `- Physical packages with manifests: **${physical.length}**`,
  `- Apps with manifests: **${appnames.length}**`,'',
  '## CLI commands','',
  'Authority: `src/cli/command-catalog.js` (a command being listed does not guarantee its execution succeeds).','');
for(const [topic,entries] of Object.entries(group(CLI_COMMAND_CATALOG,'topic')).sort(([a],[b])=>a.localeCompare(b))){
  list.push(`### ${topic} (${entries.length})`,'','| Command | Aliases | Advertised purpose |','| --- | --- | --- |');
  for(const v of entries)list.push(`| \`agentsam ${clean(v.id)}\` | ${clean((v.aliases||[]).join(', '))||'—'} | ${clean(v.summary)} |`);
  list.push('');
}
list.push('## Interactive shell commands','',
  'Authority: `src/lib/slash-commands.js`. A listed slash command is not evidence that the provider/runtime is configured.','');
for(const [lane,entries] of Object.entries(group(SLASH_COMMANDS,'lane')).sort(([a],[b])=>a.localeCompare(b))){
  list.push(`### ${lane} (${entries.length})`,'','| Command | Purpose |','| --- | --- |');
  for(const v of entries)list.push(`| \`${clean(v.cmd)}\` | ${clean(v.description)} |`);
  list.push('');
}
list.push('## Published-package catalog','',
  'Authority: `packages/catalog/generated/packages.json`. `catalog_status` and `status` are copied as recorded, not evaluated here.','',
  '| Package | Purpose | Catalog status | Operational status |','| --- | --- | --- | --- |');
for(const v of [...packages].sort((a,b)=>a.name.localeCompare(b.name))){
  list.push(`| \`${clean(v.name)}\` | ${clean(v.purpose).slice(0,240)||'Unspecified'} | ${clean(v.catalog_status)||'unknown'} | ${clean(v.status)||'unknown'} |`);
}
list.push('','## Application manifests','',
  'Authority: `apps/*/package.json`. Apps may be examples or developer tools; deployment and runtime readiness are not inferred.','',
  '| App directory | Package name | Description |','| --- | --- | --- |');
for(const name of appnames){
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'apps',name,'package.json'),'utf8'));
  list.push(`| \`apps/${name}\` | \`${clean(manifest.name)||'unnamed'}\` | ${clean(manifest.description)||'Not documented in package.json'} |`);
}
const physicalNames=physical.map(dir=>({dir,name:JSON.parse(fs.readFileSync(path.join(root,'packages',dir,'package.json'),'utf8')).name}));
const catalogNames=new Set(packages.map(p=>p.name));
const missingInCatalog=physicalNames.filter(item=>!catalogNames.has(item.name)).map(item=>item.dir);
const noPhysicalPackage=packages.filter(p=>!physicalNames.some(item=>item.name===p.name)).map(p=>p.evidence?.directory||p.id);
list.push('','## Reconciliation and proof gaps','',
  `- Physical package manifests missing catalog registrations: ${missingInCatalog.length?missingInCatalog.map(x=>'\`'+x+'\`').join(', '):'none'}.`,
  `- Catalog entries without an npm package.json (may use another distribution): ${noPhysicalPackage.length?noPhysicalPackage.map(x=>'\`'+x+'\`').join(', '):'none'}.`,
  `- Package entries needing classification: **${packages.filter(p=>p.catalog_status!=='classified').length}**.`,
  '- Next gate: attach per-command and per-package install, authorization, runtime execution, and customer-consumer receipts before claiming `READY`.','');
const result=list.join('\n');
const target=path.join(root,'docs/generated/SDK_CAPABILITY_INVENTORY.md');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==result){console.error('capability_inventory_out_of_date: npm run catalog:inventory');process.exitCode=1;}
  else console.log('capability_inventory_current');
}else{
  fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,result);
  console.log(JSON.stringify({ok:true,commands:CLI_COMMAND_CATALOG.length,slash:SLASH_COMMANDS.length,packages:packages.length,app_manifests:appnames.length,classification_missing:packages.filter(p=>p.catalog_status!=='classified').length,output:'docs/generated/SDK_CAPABILITY_INVENTORY.md'}));
}
