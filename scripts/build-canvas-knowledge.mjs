#!/usr/bin/env node
// Package real skill catalog sources for Worker execution; no filesystem reads at runtime.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadSkill } from '../src/skills/catalog.js';

const ids = ['agentsam-canvas-creation', 'agentsam-cms-ready-creation',
  'agentsam-app-fundamentals', 'agentsam-experience-delivery', 'agentsam-progression-guard'];
const entries = Object.fromEntries(ids.map(id => {
  const loaded = loadSkill(id, { references: true });
  const sha256 = createHash('sha256').update(JSON.stringify(loaded)).digest('hex');
  return [id, { ...loaded, sha256 }];
}));
const output = '// Generated by scripts/build-canvas-knowledge.mjs from the canonical SDK skill catalog.\n'
  + 'export const CANVAS_SKILLS = Object.freeze(' + JSON.stringify(entries, null, 2) + ');\n';
const target = fileURLToPath(new URL('../apps/local-studio/backend/worker/canvas-knowledge.generated.js', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('canvas_knowledge_bundle_stale');
} else {
  writeFileSync(target, output);
}
console.log('[canvas-knowledge] ' + ids.length + ' canonical skills verified');
