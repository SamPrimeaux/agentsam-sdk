#!/usr/bin/env node
/**
 * Sync public AgentSam site installables + mirrors from package truth.
 * Run on publish / before shipping static site:
 *   npm run site:sync          (repo root)
 *   npm run site:publish       (repo root — push code sections to WEBSITE_ASSETS R2)
 *   npm run build              (local-studio — runs site:sync first)
 *
 * Storage roles (CMS intended model):
 *   WEBSITE_ASSETS (R2)  — SSOT for site HTML/CSS/JS code sections
 *   DB (D1)              — editable field metadata / CMS rows
 *   SITE_CACHE (KV)      — optional edge refresh cache (when bound)
 *   env.ASSETS           — Worker static build output (SPA/shell), bootstrap only
 *
 * Pipeline:
 *   1) apps/frontend/public/site  (repo authoring copy)
 *   2) site:sync mirrors → apps/local-studio/frontend/public/site
 *   3) vite/.output packages Worker ASSETS bootstrap copy
 *   4) site:publish uploads → R2 sites/{slug}/public/** (live SSOT)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const siteRoot = path.join(root, 'apps/frontend/public/site');
const studioSite = path.join(root, 'apps/local-studio/frontend/public/site');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const installables = {
  schema: 'agentsam.installables.v1',
  generated_at: new Date().toISOString(),
  generator: 'scripts/sync-public-site.mjs',
  packages: [
    {
      id: 'agentsam-sdk',
      name: pkg.name,
      version: pkg.version,
      title: 'AgentSam SDK',
      description: pkg.description,
      npm: pkg.name,
      install: `npm i ${pkg.name}`,
      install_exact: `npm i ${pkg.name}@${pkg.version}`,
      run: 'npx agentsam',
      docs: {
        help: '/packages/sdk/help/',
        setup: '/packages/sdk/setup-guide/',
        learn: '/learn/',
      },
      repository: pkg.repository?.url || 'https://github.com/SamPrimeaux/agentsam-sdk',
    },
  ],
  copy_blocks: {
    install: `npm i ${pkg.name}`,
    install_exact: `npm i ${pkg.name}@${pkg.version}`,
    check: 'npx agentsam --version',
    inspect: 'npx agentsam inspect .',
  },
};

const outJson = path.join(siteRoot, 'global/installables.json');
fs.mkdirSync(path.dirname(outJson), { recursive: true });
fs.writeFileSync(outJson, `${JSON.stringify(installables, null, 2)}\n`);

const outJs = path.join(siteRoot, 'global/installables.js');
fs.writeFileSync(
  outJs,
  `/* generated by scripts/sync-public-site.mjs — do not edit by hand */\nwindow.AGENTSAM_INSTALLABLES = ${JSON.stringify(installables, null, 2)};\n`
);

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (entry.name === '.DS_Store') continue;
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(from, to);
    else fs.copyFileSync(from, to);
  }
}

// Stage live theme gallery into public site (catalog + demo mounts)
try {
  const { spawnSync } = await import('node:child_process');
  const stageThemes = path.join(root, 'scripts/stage-themes-to-site.mjs');
  if (fs.existsSync(stageThemes)) {
    const r = spawnSync(process.execPath, [stageThemes], { cwd: root, encoding: 'utf8' });
    if (r.status !== 0) {
      console.warn('[site:sync] themes stage skipped:', (r.stderr || r.stdout || '').trim());
    }
  }
} catch (err) {
  console.warn('[site:sync] themes stage error:', err?.message || err);
}

// Rebuild /docs/sam/* from sectioned HTML + violet docs theme
try {
  const { spawnSync } = await import('node:child_process');
  const samDocs = path.join(root, 'scripts/build-sam-docs.mjs');
  if (fs.existsSync(samDocs)) {
    const r = spawnSync(process.execPath, [samDocs], { cwd: root, encoding: 'utf8' });
    if (r.status !== 0) {
      console.warn('[site:sync] sam docs rebuild failed:', (r.stderr || r.stdout || '').trim());
    } else {
      console.log('[site:sync] sam docs rebuilt');
    }
  }
} catch (err) {
  console.warn('[site:sync] sam docs rebuild error:', err?.message || err);
}

// Refresh /learn/ from donor when present (Downloads or AGENTSAM_LEARN_SOURCE)
try {
  const { spawnSync } = await import('node:child_process');
  const learnBuild = path.join(root, 'scripts/build-learn-site.mjs');
  if (fs.existsSync(learnBuild) && process.env.AGENTSAM_LEARN_SOURCE) {
    const r = spawnSync(process.execPath, [learnBuild], { cwd: root, encoding: 'utf8' });
    if (r.status !== 0) {
      console.warn('[site:sync] learn rebuild skipped:', (r.stderr || r.stdout || '').trim());
    }
  }
} catch (err) {
  console.warn('[site:sync] learn rebuild error:', err?.message || err);
}

// Legacy Worker/asset probe: homepage.html is a full copy of home/
const homeIndex = path.join(siteRoot, 'home/index.html');
const homepageLegacy = path.join(siteRoot, 'homepage.html');
if (fs.existsSync(homeIndex)) {
  fs.copyFileSync(homeIndex, homepageLegacy);
}

copyDir(siteRoot, studioSite);

console.log(
  JSON.stringify(
    {
      ok: true,
      version: pkg.version,
      wrote: [
        path.relative(root, outJson),
        path.relative(root, outJs),
        path.relative(root, studioSite),
      ],
    },
    null,
    2
  )
);
