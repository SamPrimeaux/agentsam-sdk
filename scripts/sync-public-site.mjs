#!/usr/bin/env node
/**
 * Sync public AgentSam site installables + mirrors from package truth.
 * Run on publish / before shipping static site:
 *   npm run site:sync          (repo root)
 *   npm run site:publish       (repo root — push code sections to WEBSITE_ASSETS R2)
 *   npm run build              (local-studio — runs site:sync first)
 *
 * Storage roles (CMS intended model):
 *   WEBSITE_ASSETS (R2)  — SSOT for site HTML/CSS/JS code sections
 *   DB (D1)              — editable field metadata / CMS rows
 *   SITE_CACHE (KV)      — optional edge refresh cache (when bound)
 *   env.ASSETS           — Worker static build output (SPA/shell), bootstrap only
 *
 * Pipeline:
 *   1) apps/frontend/public/site  (repo authoring copy)
 *   2) site:sync mirrors → apps/local-studio/frontend/public/site
 *   3) vite/.output packages Worker ASSETS bootstrap copy
 *   4) site:publish uploads → R2 sites/{slug}/public/** (live SSOT)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const siteRoot = path.join(root, 'apps/frontend/public/site');
const studioSite = path.join(root, 'apps/local-studio/frontend/public/site');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const installables = {
  schema: 'agentsam.installables.v1',
  generated_at: new Date().toISOString(),
  generator: 'scripts/sync-public-site.mjs',
  packages: [
    {
      id: 'agentsam-sdk',
      name: pkg.name,
      version: pkg.version,
      title: 'AgentSam SDK',
      description: pkg.description,
      npm: pkg.name,
      install: `npm i ${pkg.name}`,
      install_exact: `npm i ${pkg.name}@${pkg.version}`,
      run: 'npx agentsam',
      docs: {
        help: '/packages/sdk/help/',
        setup: '/packages/sdk/setup-guide/',
        learn: '/learn/',
      },
      repository: pkg.repository?.url || 'https://github.com/SamPrimeaux/agentsam-sdk',
    },
    {
      id: 'agentsamd',
      name: 'agentsamd',
      version: '0.1.0',
      title: 'AgentSam Machine Daemon',
      description:
        'Local machine/runtime daemon (agentsam.runtime.v1). Distinct from agentsam-go-worker (hosted service).',
      kind: 'daemon',
      runtime_adapter: 'agentsamd',
      protocol: 'agentsam.runtime.v1',
      install: 'npx agentsam runtime install --yes',
      setup: 'npx agentsam setup runtime --profile my_computer --yes',
      run: '~/.agentsam/bin/agentsamd',
      platforms: ['darwin-arm64', 'darwin-amd64', 'linux-amd64', 'linux-arm64'],
      launch_agent: 'com.inneranimalmedia.agentsamd',
      source: 'apps/agentsam-go-worker/runtime/cmd/agentsamd',
      distinct_from: 'agentsam-go-worker',
      docs: {
        protocol: '/docs/architecture/AGENTSAM_RUNTIME_PROTOCOL.md',
        readme: '/apps/agentsamd/README.md',
      },
      repository: pkg.repository?.url || 'https://github.com/SamPrimeaux/agentsam-sdk',
    },
    {
      id: 'agentsam-go-worker',
      name: '@inneranimalmedia/agentsam-go-worker',
      version: '0.1.0',
      title: 'AgentSam Go Worker',
      description:
        'Hosted Go SERVICE (Cloudflare Worker + Container). Not the user-machine daemon — see agentsamd.',
      kind: 'service',
      install: 'npx agentsam go --cloudflare agentsam-go-worker --dry-run',
      run: 'agentsam go --cloudflare agentsam-go-worker',
      distinct_from: 'agentsamd',
      source: 'apps/agentsam-go-worker',
      repository: pkg.repository?.url || 'https://github.com/SamPrimeaux/agentsam-sdk',
    },
  ],
  copy_blocks: {
    install: `npm i ${pkg.name}`,
    install_exact: `npm i ${pkg.name}@${pkg.version}`,
    check: 'npx agentsam --version',
    inspect: 'npx agentsam inspect .',
    runtime_install: 'npx agentsam runtime install --yes',
    setup_runtime: 'npx agentsam setup runtime --profile my_computer --yes',
  },
};

const outJson = path.join(siteRoot, 'global/installables.json');

// Keep generated output idempotent. If the payload is unchanged apart from
// generated_at, preserve the prior timestamp instead of dirtying the repo on
// every site:sync / prepublishOnly run.
if (fs.existsSync(outJson)) {
  try {
    const previous = JSON.parse(fs.readFileSync(outJson, 'utf8'));
    const comparable = {
      ...installables,
      generated_at: previous.generated_at,
    };

    if (
      typeof previous.generated_at === 'string' &&
      JSON.stringify(previous) === JSON.stringify(comparable)
    ) {
      installables.generated_at = previous.generated_at;
    }
  } catch {
    // Invalid/missing prior output: generate a fresh timestamp normally.
  }
}

fs.mkdirSync(path.dirname(outJson), { recursive: true });
fs.writeFileSync(outJson, `${JSON.stringify(installables, null, 2)}\n`);

const outJs = path.join(siteRoot, 'global/installables.js');
fs.writeFileSync(
  outJs,
  `/* generated by scripts/sync-public-site.mjs — do not edit by hand */\nwindow.AGENTSAM_INSTALLABLES = ${JSON.stringify(installables, null, 2)};\n`
);

function ensureTrademarkNotice(dir) {
  if (!fs.existsSync(dir)) return;
  const notice = '  <meta name="third-party-trademark-notice" content="Third-party names and trademarks belong to their respective owners; compatibility references do not imply sponsorship, endorsement, partnership, collaboration, or affiliation." />\n';
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const target = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      ensureTrademarkNotice(target);
      continue;
    }
    if (!entry.isFile() || !entry.name.endsWith('.html')) continue;
    let html = fs.readFileSync(target, 'utf8');
    if (html.includes('third-party-trademark-notice')) continue;
    if (html.includes('</head>')) {
      html = html.replace('</head>', notice + '</head>');
      fs.writeFileSync(target, html);
    }
  }
}

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (entry.name === '.DS_Store') continue;
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) copyDir(from, to);
    else fs.copyFileSync(from, to);
  }
}

// Stage live theme gallery into public site (catalog + demo mounts)
try {
  const { spawnSync } = await import('node:child_process');
  const stageThemes = path.join(root, 'scripts/stage-themes-to-site.mjs');
  if (fs.existsSync(stageThemes)) {
    const r = spawnSync(process.execPath, [stageThemes], { cwd: root, encoding: 'utf8' });
    if (r.status !== 0) {
      console.warn('[site:sync] themes stage skipped:', (r.stderr || r.stdout || '').trim());
    }
  }
} catch (err) {
  console.warn('[site:sync] themes stage error:', err?.message || err);
}

// Rebuild /docs/sam/* from sectioned HTML + violet docs theme
try {
  const { spawnSync } = await import('node:child_process');
  const samDocs = path.join(root, 'scripts/build-sam-docs.mjs');
  if (fs.existsSync(samDocs)) {
    const r = spawnSync(process.execPath, [samDocs], { cwd: root, encoding: 'utf8' });
    if (r.status !== 0) {
      console.warn('[site:sync] sam docs rebuild failed:', (r.stderr || r.stdout || '').trim());
    } else {
      console.log('[site:sync] sam docs rebuilt');
    }
  }
} catch (err) {
  console.warn('[site:sync] sam docs rebuild error:', err?.message || err);
}

// Refresh /learn/ from donor when present (Downloads or AGENTSAM_LEARN_SOURCE)
try {
  const { spawnSync } = await import('node:child_process');
  const learnBuild = path.join(root, 'scripts/build-learn-site.mjs');
  if (fs.existsSync(learnBuild) && process.env.AGENTSAM_LEARN_SOURCE) {
    const r = spawnSync(process.execPath, [learnBuild], { cwd: root, encoding: 'utf8' });
    if (r.status !== 0) {
      console.warn('[site:sync] learn rebuild skipped:', (r.stderr || r.stdout || '').trim());
    }
  }
} catch (err) {
  console.warn('[site:sync] learn rebuild error:', err?.message || err);
}

// Legacy Worker/asset probe: homepage.html is a full copy of home/
const homeIndex = path.join(siteRoot, 'home/index.html');
const homepageLegacy = path.join(siteRoot, 'homepage.html');
if (fs.existsSync(homeIndex)) {
  fs.copyFileSync(homeIndex, homepageLegacy);
}

// Every public HTML document carries the same compact interoperability/trademark
// notice so attribution survives standalone pages as well as the shared footer.
ensureTrademarkNotice(siteRoot);

// Theme gallery is regenerated as a canonical projection. Remove its mirror
// first so renamed/deleted prebuilds cannot survive as stale public routes.
const studioThemes = path.join(studioSite, 'themes');
if (fs.existsSync(studioThemes)) {
  fs.rmSync(studioThemes, { recursive: true, force: true });
}

copyDir(siteRoot, studioSite);

console.log(
  `[site:sync] public site synced (marketing + CMS + SEO content) → ${path.relative(root, studioSite)}`,
);
console.log(
  JSON.stringify(
    {
      ok: true,
      version: pkg.version,
      wrote: [
        path.relative(root, outJson),
        path.relative(root, outJs),
        path.relative(root, studioSite),
      ],
    },
    null,
    2
  )
);
