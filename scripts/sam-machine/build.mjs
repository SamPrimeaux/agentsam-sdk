#!/usr/bin/env node
/**
 * Materialize the REAL installed SAM kernel catalog, six-language operation
 * identifiers, and evidence-backed HTML/MD audit. Does not create fake tools.
 *
 * node scripts/sam-machine/build.mjs --out /tmp/sam-machine-build --project .
 * node scripts/sam-machine/build.mjs --out /tmp/sam-machine-build --verify
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { AgentSamClient, createSamOS } from '../../src/sam/index.js';
import manifest from '../../protocol/capabilities/manifest.json' with { type: 'json' };
import { generateCapabilityTypes } from './generate-types.mjs';

const ROOT=path.resolve(fileURLToPath(new URL('../../', import.meta.url)));
const args=process.argv.slice(2);
const value=flag=>{const index=args.indexOf(flag);return index>=0?args[index+1]:undefined;};
if (args.includes('--help')){
  process.stdout.write('Usage: node scripts/sam-machine/build.mjs --out DIR [--project DIR] [--verify]\n');
  process.exit(0);
}
const output=value('--out');
if(!output)throw new Error('sam_build_out_required');
const out=path.resolve(output);
const project=path.resolve(value('--project')||ROOT);
const os=createSamOS();
const sam=new AgentSamClient({os,cwd:project});
const all=os.list().map(op=>({
  id:op.id,version:op.version,module:op.module,risk:op.risk,
  side_effects:op.execution.sideEffects,network:op.execution.network,
  handler_bound:true, verified:false,source:'sam-core-or-installed-pack',
}));
const ids=new Set(all.map(x=>x.id));
const capabilities=Object.entries(manifest.capabilities||{}).map(([id,op])=>({
  id,version:op.version||null,status:op.status||'unknown',
  family:op.domain||'unknown',source:'capability-manifest',
  sam_handler_bound:ids.has(id), verified:false,
}));
const missing=capabilities.filter(x=>!x.sam_handler_bound);
await fs.mkdir(out,{recursive:true});
const pretty=obj=>JSON.stringify(obj,null,2)+'\n';
const catalog={
  schema:'sam.machine.catalog.v1',name:'Systematic Autonomous Machinery',
  generated_at:new Date().toISOString(),
  source_commit:spawnSync('git',['rev-parse','--short','HEAD'],{cwd:ROOT,encoding:'utf8'}).stdout.trim(),
  operation_count:all.length,declared_manifest_count:capabilities.length,
  operations:all,capabilities,unbound_to_sam:missing.map(x=>x.id),
  caveat:'Catalog membership does not prove authorization, runtime availability, or verified execution.',
};
await fs.writeFile(path.join(out,'catalog.json'),pretty(catalog));

const names=all.map(x=>x.id).sort();
const q=JSON.stringify;
const bindings=path.join(out,'bindings');
await fs.mkdir(bindings,{recursive:true});
await fs.writeFile(path.join(bindings,'capabilities.generated.ts'),generateCapabilityTypes(all));
await fs.writeFile(path.join(bindings,'sam-operation-ids.d.ts'),
  '// Generated from real SAM operations; IDs only, not an executor.\nexport type SamOperationId =\n  '+names.map(q).join(' |\n  ')+';\n');
await fs.writeFile(path.join(bindings,'sam_operations.py'),
  '# Generated SAM operation IDs; the Python client must still verify host capability.\nSAM_OPERATION_IDS = (\n'+names.map(n=>'    '+q(n)+',').join('\n')+'\n)\n');
await fs.writeFile(path.join(bindings,'operations.go'),
  '// Code generated by SAM; identifiers are not Go handler implementations.\npackage samops\n\nvar OperationIDs = []string{\n'+names.map(n=>'  '+q(n)+',').join('\n')+'\n}\n');
await fs.writeFile(path.join(bindings,'operations.rs'),
  '// Generated operation IDs; Rust executors are independently authorized.\npub const OPERATION_IDS: &[&str] = &[\n'+names.map(n=>'    '+q(n)+',').join('\n')+'\n];\n');
await fs.writeFile(path.join(bindings,'operations.hpp'),
  '// Generated identifiers; C++ bindings require real native/remote host adapters.\n#pragma once\n#include <array>\n#include <string_view>\nnamespace sam { inline constexpr std::array<std::string_view, '+names.length+'> operation_ids = {\n'+names.map(n=>'  '+q(n)+',').join('\n')+'\n}; }\n');

let repoResult=null;
if(args.includes('--verify')||args.includes('--inspect')){
  repoResult=await sam.invoke('repository.inspect',{root:project});
  if(!repoResult.ok)throw new Error('sam_repository_inspect_failed:'+(repoResult.error?.code||'unknown'));
}
const findings=[
  {id:'CAT-001',title:'SAM operations with installed handlers',
    detail:all.length+' actual operations in the current instance. Each is registered and has a handler; no remote/approval claim is inferred.',
    evidenceRefs:repoResult?['repository-inspection-receipt']:[]},
  {id:'CAT-002',title:'Separate capability declarations require host adapters',
    detail:missing.length+' manifest operation IDs are not in this isolated SAM OS. They may belong to other authorized hosts; this is not proof that their implementations are missing.',
    evidenceRefs:repoResult?['repository-inspection-receipt']:[]},
];
const report=await sam.invoke('artifact.render',{
  title:'SAM — Machine Build & Execution Catalog',
  summary:'Source-derived audit of the installed Systematic Autonomous Machinery kernel. Specialist implementations remain with their host owners. Registration is not verification.',
  findings,
  evidence:repoResult?[{ref:'repository-inspection-receipt',label:repoResult.receipt.id,source:'repository.inspect; local SAM receipt'}]:[],
  steps:[
    {id:'GATE-01',title:'Bind authorized specialists',acceptance:'Each manifest ID routes to a named real host, rejects missing handlers, and returns a receipt.'},
    {id:'GATE-02',title:'Certify language parity',acceptance:'Each language executes identical signed fixtures and matches authorization/result semantics.'},
    {id:'GATE-03',title:'Deliver verified work',acceptance:'Run evidence renders to HTML/Markdown through artifact.render, with no fabricated findings.'},
  ],
});
if(!report.ok)throw new Error('sam_artifact_render_failed');
for(const [name,body] of Object.entries(report.data.files))await fs.writeFile(path.join(out,name),body);
await fs.writeFile(path.join(out,'manifest.json'),pretty(report.data.manifest));
if(repoResult)await fs.writeFile(path.join(out,'inspection-receipt.json'),pretty(repoResult.receipt));

const checks=[];
if(args.includes('--verify')){
  const tests=[
    ['js-public-api',process.execPath,['--test','test/integration/sam-machine-public-api.test.mjs']],
    ['python-public-api','python3',['-m','unittest','discover','-s','python/tests','-p','test_public_client.py']],
  ];
  for(const [name,command,argv] of tests){
    const result=spawnSync(command,argv,{cwd:ROOT,encoding:'utf8',timeout:120000,
      env:{...process.env,PYTHONPATH:path.join(ROOT,'python'),AGENTSAM_NODE:process.execPath}});
    checks.push({name,ok:result.status===0,exit_code:result.status,tail:(result.stdout+'\n'+result.stderr).trim().split('\n').slice(-10)});
  }
}
const acceptance={
  schema:'sam.machine.acceptance.v1',source_commit:catalog.source_commit,generated_at:catalog.generated_at,
  kernel_handlers:all.length,generated_language_id_projections:['typescript','python','go','rust','cpp'],
  language_clients_verified:['javascript','python-local-safe-subset'],
  language_clients_not_certified:['typescript-typed-public-client','go','rust','cpp','python-remote-acp'],
  checks,ok:checks.every(x=>x.ok),release_complete:false,
  release_blockers:['typescript','go','rust','cpp','cms','copro','media','iam_write_scope','durable_execution','artifact_storage'],
};
await fs.writeFile(path.join(out,'acceptance.json'),pretty(acceptance));
process.stdout.write(pretty({ok:acceptance.ok,out,kernel:all.length,capabilities:capabilities.length,unbound_to_sam:missing.length,
  tests:checks.map(x=>({name:x.name,ok:x.ok})),reports:['report.html','report.md','catalog.json','acceptance.json','manifest.json']}));
if(!acceptance.ok)process.exitCode=1;
