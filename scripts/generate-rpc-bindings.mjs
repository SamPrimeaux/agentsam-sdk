import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const protoPath = join(root, 'protocol/rpc/v1/knowledge.proto');
const outputPath = join(root, 'src/rpc/generated/knowledge-v1.js');
const source = readFileSync(protoPath, 'utf8');
const clean = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
const packageName = clean.match(/\bpackage\s+([\w.]+)\s*;/)?.[1];
if (!packageName) throw new Error('knowledge.proto is missing a package declaration');

const schemas = {};
for (const match of clean.matchAll(/\bmessage\s+(\w+)\s*\{([^{}]*)\}/g)) {
  const [, name, body] = match;
  const fields = [];
  for (const field of body.matchAll(/\b(optional\s+)?(repeated\s+)?([A-Za-z_][\w.]*)\s+([A-Za-z_][\w]*)\s*=\s*(\d+)\s*;/g)) {
    fields.push({
      tag: Number(field[5]),
      name: field[4],
      type: field[3],
      optional: Boolean(field[1]),
      repeated: Boolean(field[2]),
    });
  }
  schemas[name] = fields.sort((a, b) => a.tag - b.tag);
}

const serviceMatch = clean.match(/\bservice\s+(\w+)\s*\{([\s\S]*?)\}/);
if (!serviceMatch) throw new Error('knowledge.proto is missing a service declaration');
const serviceName = serviceMatch[1];
const methods = {};
for (const rpc of serviceMatch[2].matchAll(/\brpc\s+(\w+)\s*\(\s*(stream\s+)?([\w.]+)\s*\)\s+returns\s*\(\s*(stream\s+)?([\w.]+)\s*\)\s*;/g)) {
  const name = rpc[1];
  methods[name] = {
    path: `/${packageName}.${serviceName}/${name}`,
    requestType: rpc[3].split('.').pop(),
    responseType: rpc[5].split('.').pop(),
    clientStreaming: Boolean(rpc[2]),
    serverStreaming: Boolean(rpc[4]),
  };
}

const hash = createHash('sha256').update(source).digest('hex');
const rendered = `// GENERATED by scripts/generate-rpc-bindings.mjs. Do not edit by hand.\n` +
  `export const PACKAGE = ${JSON.stringify(packageName)};\n` +
  `export const PROTO_SHA256 = ${JSON.stringify(hash)};\n` +
  `export const SCHEMAS = Object.freeze(${JSON.stringify(schemas, null, 2)});\n` +
  `export const SERVICE = Object.freeze(${JSON.stringify({ name: serviceName, methods }, null, 2)});\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(outputPath, 'utf8'); } catch {}
  if (current !== rendered) {
    console.error('RPC bindings are stale. Run `npm run rpc:generate`.');
    process.exit(1);
  }
  console.log(`verify-rpc OK ${packageName}.${serviceName} ${hash.slice(0, 12)}`);
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, rendered);
  console.log(`generated ${outputPath.slice(root.length + 1)} ${hash.slice(0, 12)}`);
}
