#!/usr/bin/env node
// Generates docs/native-capability-ledger.md from the source of truth:
//   generate_handler! in src-tauri/src/main.rs  ->  module implementing it
//   frontend consumers discovered by scanning app/package sources for the command id
//   Rust tests discovered per implementing module
// The *Live* column is an explicit, hand-maintained claim (LIVE below), never inferred from
// the binary: only commands somebody actually exercised in a packaged build are listed.
// `--check` fails when the committed ledger is missing a handler or lists one main.rs no
// longer registers.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const shellRoot = resolve(here, "..");
const repoRoot = resolve(shellRoot, "../..");
const mainRs = join(shellRoot, "src-tauri/src/main.rs");
const commandsDir = join(shellRoot, "src-tauri/src/commands");
const ledgerPath = join(shellRoot, "docs/native-capability-ledger.md");

// Packaged-build verification claims. Everything else is "not verified".
export const LIVE = {
  ensure_agentsamd: "user-verified (terminal PTY)",
  agentsamd_health: "user-verified (terminal PTY)",
  agentsamd_pairing_token: "user-verified (terminal PTY)",
  native_color_panel_supported: "self-test, packaged build",
  native_color_panel_open: "self-test, packaged build",
  native_selftest_ack: "self-test, packaged build",
};

export function parseHandlers(source) {
  const block = source.match(/generate_handler!\[([\s\S]*?)\]\)/)?.[1] ?? "";
  return block
    .split("\n")
    .map((line) => line.replace(/\/\/.*$/, "").trim().replace(/,$/, ""))
    .filter(Boolean)
    .map((path) => {
      const parts = path.split("::");
      return { command: parts[parts.length - 1], module: parts.slice(0, -1).join("::") };
    });
}

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    if (["node_modules", "dist", "desktop-dist", "target", ".output", ".agentsam", "generated"].includes(name)) continue;
    const full = join(dir, name);
    const info = statSync(full);
    if (info.isDirectory()) walk(full, out);
    else if (/\.(ts|tsx|js|mjs)$/.test(name) && !name.endsWith(".d.ts")) out.push(full);
  }
  return out;
}

function moduleFile(module) {
  const name = module.split("::").pop();
  const candidate = join(commandsDir, `${name}.rs`);
  if (existsSync(candidate)) return candidate;
  if (module === "tray") return join(shellRoot, "src-tauri/src/tray.rs");
  return null;
}

export function buildRows() {
  const handlers = parseHandlers(readFileSync(mainRs, "utf8"));
  const sources = [
    join(repoRoot, "apps/local-studio/frontend/src"),
    join(repoRoot, "apps/local-studio/frontend/agentsam"),
    join(repoRoot, "apps/local-studio/scripts"),
    join(repoRoot, "apps/cad-creator/frontend/src"),
    join(repoRoot, "packages"),
  ].flatMap((dir) => walk(dir));
  const contents = new Map(sources.map((file) => [file, readFileSync(file, "utf8")]));
  return handlers.map(({ command, module }) => {
    const pattern = new RegExp(`["'\`]${command}["'\`]`);
    const consumers = [];
    const tests = [];
    for (const [file, text] of contents) {
      if (!pattern.test(text)) continue;
      const rel = relative(repoRoot, file);
      if (rel.includes("native-capability-ledger")) continue;
      (/\.test\.|smoke-/.test(rel) ? tests : consumers).push(rel);
    }
    const file = moduleFile(module);
    const rustTests = file ? /#\[cfg\(test\)\]/.test(readFileSync(file, "utf8")) : false;
    return {
      command,
      module,
      impl: file ? relative(shellRoot, file) : "?",
      consumers: consumers.slice(0, 2),
      tests: tests.slice(0, 2),
      rustTests,
      live: LIVE[command] ?? "not verified",
    };
  });
}

function render(rows) {
  const lines = [
    "# Native capability ledger",
    "",
    "Generated by `scripts/native-capability-ledger.mjs` from `generate_handler!` in `src-tauri/src/main.rs`.",
    "Columns are mechanical facts: *Frontend consumer* = a source file that invokes the id, *Tests* = a",
    "frontend/script file asserting it (or Rust unit tests in the implementing module), *Live* = verified in a",
    "packaged build (hand-maintained `LIVE` map; \"not verified\" is the default and is not a failure claim).",
    "",
    "| Command | Implementation | Frontend consumer | Tests | Live |",
    "|---|---|---|---|---|",
  ];
  for (const row of rows) {
    const consumer = row.consumers.length ? row.consumers.map((c) => `\`${c}\``).join("<br>") : "**none (unwired)**";
    const tests = [row.rustTests ? "Rust tests in module (not per-command)" : null, ...row.tests.map((t) => `\`${t}\``)].filter(Boolean).join("<br>") || "none";
    lines.push(`| \`${row.command}\` | \`${row.impl}\` | ${consumer} | ${tests} | ${row.live} |`);
  }
  return `${lines.join("\n")}\n`;
}

export function ledgerCommands(markdown) {
  return [...markdown.matchAll(/^\| `([a-z_0-9]+)` \|/gm)].map((m) => m[1]).sort();
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  if (args.includes("--check")) {
    const expected = parseHandlers(readFileSync(mainRs, "utf8")).map((h) => h.command).sort();
    const actual = existsSync(ledgerPath) ? ledgerCommands(readFileSync(ledgerPath, "utf8")) : [];
    const missing = expected.filter((c) => !actual.includes(c));
    const stale = actual.filter((c) => !expected.includes(c));
    if (missing.length || stale.length) {
      console.error(`ledger drift: missing=${missing.join(",") || "-"} stale=${stale.join(",") || "-"}`);
      process.exit(1);
    }
    console.log(`ledger ok (${expected.length} commands)`);
  } else {
    mkdirSync(dirname(ledgerPath), { recursive: true });
    const rows = buildRows();
    writeFileSync(ledgerPath, render(rows));
    console.log(`wrote ${relative(repoRoot, ledgerPath)} (${rows.length} commands)`);
  }
}
