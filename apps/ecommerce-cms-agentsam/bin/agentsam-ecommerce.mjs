function scaffold(destination) {
  if (!destination) {
    throw new Error(
      "Provide an empty destination directory."
    );
  }

  if (missing.length) {
    throw new Error(
      "Package unavailable: " +
      missing.join(", ")
    );
  }

  const target = path.resolve(destination);

  if (
    target === app ||
    target.startsWith(app + path.sep)
  ) {
    throw new Error(
      "Use a destination outside the installed package."
    );
  }

  if (
    fs.existsSync(target) &&
    fs.readdirSync(target).length
  ) {
    throw new Error(
      "Destination must be empty."
    );
  }

  fs.mkdirSync(target, {
    recursive: true
  });

  const appTarget = path.join(
    target,
    "apps",
    "ecommerce-cms-agentsam"
  );

  const filter = file => {
    const relative = path.relative(app, file);

    if (!relative) {
      return true;
    }

    const parts = relative.split(path.sep);

    if (
      parts.some(part =>
        ["node_modules", ".git", ".wrangler", "dist"].includes(part)
      )
    ) {
      return false;
    }

    return !relative.endsWith(".tgz");
  };

  fs.cpSync(
    app,
    appTarget,
    {
      recursive: true,
      filter
    }
  );

  fs.mkdirSync(
    path.join(target, "db"),
    { recursive: true }
  );

  fs.copyFileSync(
    path.join(
      app,
      "templates",
      "db",
      "schema.sql"
    ),
    path.join(
      target,
      "db",
      "schema.sql"
    )
  );

  fs.writeFileSync(
    path.join(
      target,
      "db",
      "seed-customer-bootstrap.sql"
    ),
    scaffoldBootstrapSql()
  );

  fs.mkdirSync(
    path.join(target, "public"),
    { recursive: true }
  );

  fs.writeFileSync(
    path.join(
      target,
      "public",
      "index.html"
    ),
    '<!doctype html>' +
    '<meta charset="utf-8">' +
    '<meta http-equiv="refresh" content="0;url=/admin/home">' +
    '<title>Ecommerce Admin</title>\n'
  );

  fs.mkdirSync(
    path.join(target, "scripts"),
    { recursive: true }
  );

  fs.copyFileSync(
    path.join(
      app,
      "templates",
      "scripts",
      "sync-app-frontend.mjs"
    ),
    path.join(
      target,
      "scripts",
      "sync-app-frontend.mjs"
    )
  );

  fs.writeFileSync(
    path.join(
      target,
      "wrangler.toml"
    ),
    scaffoldWrangler("my-ecommerce")
  );

  fs.writeFileSync(
    path.join(
      target,
      ".gitignore"
    ),
    [
      "node_modules/",
      ".wrangler/",
      "dist/",
      ".env*",
      ".dev.vars*",
      "apps/ecommerce-cms-agentsam/frontend/dist/",
      ""
    ].join("\n")
  );

  const pkg = {
    name: "my-ecommerce",
    version: "0.1.0",
    private: true,
    type: "module",

    workspaces: [
      "apps/ecommerce-cms-agentsam",
      "apps/ecommerce-cms-agentsam/frontend"
    ],

    scripts: {
      "app:frontend:sync":
        "node scripts/sync-app-frontend.mjs",

      build:
        "npm run build --workspace=@inneranimalmedia/ecommerce-dashboard && npm run app:frontend:sync",

      dev:
        "npm run build && wrangler dev",

      deploy:
        "npm run build && wrangler deploy",

      ecommerce:
        "node apps/ecommerce-cms-agentsam/bin/agentsam-ecommerce.mjs",

      "db:migrate:local":
        "wrangler d1 execute my-ecommerce --local --file=db/schema.sql",

      "db:migrate:remote":
        "wrangler d1 execute my-ecommerce --remote --file=db/schema.sql"
    },

    devDependencies: {
      wrangler: "4.145.0"
    }
  };

  fs.writeFileSync(
    path.join(
      target,
      "package.json"
    ),
    JSON.stringify(
      pkg,
      null,
      2
    ) + "\n"
  );

  fs.writeFileSync(
    path.join(
      target,
      "SETUP.md"
    ),
`# Your ecommerce app

This project was scaffolded from @inneranimalmedia/ecommerce-cms-agentsam.

1. Edit db/seed-customer-bootstrap.sql.
2. Run npm install.
3. Run npm run build.
4. Provision D1, R2, KV, Queue and AI bindings.
5. Replace placeholder resource IDs in wrangler.toml.
6. Apply db/schema.sql and db/seed-customer-bootstrap.sql.
7. Configure provider secrets.
8. Run npm run dev.

Fuel & Free Time is customer #1. Its branding, products,
campaigns, media, credentials and business data are not
package defaults.
`
  );

  console.log(
    "Scaffold created: " +
    target +
    "\nRead SETUP.md before deploying."
  );
}

try {
  if (command === "info") console.log(JSON.stringify(manifest, null, 2));
  else if (command === "doctor") {
    const packageJsonPath = path.join(app, "package.json");
    const frontendPackageJsonPath = path.join(app, "frontend", "package.json");
    const binPath = path.join(app, manifest.bin || "");

    const packageJson = fs.existsSync(packageJsonPath)
      ? JSON.parse(fs.readFileSync(packageJsonPath, "utf8"))
      : null;

    const contractConsistent =
      packageJson?.name === manifest.package &&
      packageJson?.bin?.["agentsam-ecommerce"] === manifest.bin &&
      manifest.runtime?.local_preview === "ready" &&
      manifest.runtime?.source_scaffold === "ready";

    const runnable =
      missing.length === 0 &&
      fs.existsSync(binPath) &&
      fs.existsSync(frontendPackageJsonPath);

    console.log(
      JSON.stringify(
        {
          app_id: manifest.id,
          package_root: app,
          missing,
          source: {
            frontend: fs.existsSync(frontendPackageJsonPath)
          },
          runtime: {
            package_json: fs.existsSync(packageJsonPath),
            runnable
          },
          manifest_runtime: {
            local_preview: manifest.runtime?.local_preview ?? null,
            source_scaffold: manifest.runtime?.source_scaffold ?? null
          },
          contract_consistent: contractConsistent,
          source_ready: !missing.length,
          deployment_ready: false
        },
        null,
        2,
      ),
    );

    if (!runnable || !contractConsistent) process.exitCode = 1;
  } else if (command === "scaffold") scaffold(args[0]);
  else if (command === "preview") {
    if (missing.length) throw new Error("Run doctor first.");
    const result = spawnSync(
      process.platform === "win32"
        ? "npm.cmd"
        : "npm",
      [
        "run",
        "dev",
        "--prefix",
        path.join(app, "frontend"),
        "--",
        ...args
      ],
      {
        cwd: app,
        stdio: "inherit"
      }
    );
    if (result.error) throw result.error;
    process.exitCode = result.status ?? 1;
  } else if (["help", "--help", "-h"].includes(command)) {
    console.log("agentsam-ecommerce info | doctor | preview | scaffold <empty-directory>");
  } else throw new Error("Unknown agentsam-ecommerce command: " + command);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
