import assert from 'node:assert/strict';
import test from 'node:test';
import {readFileSync,existsSync,readdirSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const studio=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=relative=>readFileSync(path.join(studio,relative),'utf8');

test('Online Store uses the live Theme Store catalog and keeps preview bytes out of the SDK release',()=>{
 const stage=read('scripts/stage-console-host.mjs');
 const hostConfig=read('frontend/public/admin/host-config.js');
 const browser=read('frontend/public/admin/js/website-theme-browser.js');
 const catalog=read('backend/worker/studio-website-theme-catalog.js');
 const worker=read('backend/worker/index.js');
 const plugin=read('scripts/theme-surfaces-plugin.mjs');
 const inventory=read('frontend/src/lib/themes/inventory.ts');
 const themeStorePage=read('frontend/src/components/themes/ThemeStorePage.tsx');
 assert.match(hostConfig,/__AGENTSAM_WEBSITE_THEMES_ENDPOINT = \"\/api\/admin\/website-themes\"/);
 assert.match(browser,/window\.__AGENTSAM_WEBSITE_THEMES_ENDPOINT/);
 assert.match(browser,/preview_url/);
 assert.match(catalog,/https:\/\/themes\.inneranimalmedia\.com\/api\/catalog/);
 assert.match(catalog,/allowPreview/);
 assert.match(worker,/handleStudioWebsiteThemeCatalog/);
 assert.match(plugin,/inneranimalmedia-theme-store/);
 assert.doesNotMatch(plugin,/discoverThemeSurfaces|readdirSync|packages\/theme-/,'Local Studio must not discover or emit storefront package previews');
 assert.doesNotMatch(inventory,/virtual:agentsam-theme-inventory|discoverThemeSurfaces|listThemeStoreProducts|installThemeDraft/);
 assert.match(inventory,/\/api\/studio\/themes/);
 assert.match(themeStorePage,/https:\/\/themes\.inneranimalmedia\.com\//);
 assert.doesNotMatch(themeStorePage,/data-theme-id|ThemePreview|listStudioThemes/);
 assert.doesNotMatch(stage,/sync-theme-store-previews|listThemeStoreProducts|themeSlugs|previewSource/);
 assert.match(stage,/Remove only former website preview subdirectories/);
 assert.match(stage,/removeThemeStorePreviewMirrors/);
 assert.doesNotMatch(stage,/rmSync\(path\.join\(compiledRoot, 'themes'/,'SDK must preserve first-party /themes assets');
 const hasLocalPreviewDemos=root=>existsSync(root)&&readdirSync(root,{withFileTypes:true}).some(entry=>entry.isDirectory()&&(existsSync(path.join(root,entry.name,'index.html'))||existsSync(path.join(root,entry.name,'demo/index.html'))));
 assert.ok(!hasLocalPreviewDemos(path.join(studio,'frontend/public/themes')),'SDK must not retain Theme Store demo files');
 assert.ok(!hasLocalPreviewDemos(path.join(studio,'.output/public/themes')),'hosted output must not contain Theme Store demo files');
 assert.ok(!existsSync(path.join(studio,'frontend/public/site/themes')),'SDK must not retain the former local theme gallery mirror');
 assert.ok(!existsSync(path.join(studio,'frontend/public/ecommerce-cms-agentsam/admin/data/theme-products.json')),'SDK must not stage a duplicate Theme Store catalog snapshot');
});
